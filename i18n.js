const supported = ['en', 'zh'];
let language = 'en';
try { const saved = localStorage.getItem('epubloom.language'); if (supported.includes(saved)) language = saved; } catch { /* The language switch also works without storage. */ }

export function getLanguage() { return language; }
export function t(key, values = {}) {
  const message = messages[language][key] ?? messages.en[key] ?? key;
  return message.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}

function renderLanguage() {
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  for (const [attribute, target] of [['data-i18n', 'textContent'], ['data-i18n-html', 'innerHTML']]) {
    document.querySelectorAll(`[${attribute}]`).forEach(element => { element[target] = t(element.getAttribute(attribute)); });
  }
  for (const [attribute, target] of [['data-i18n-placeholder', 'placeholder'], ['data-i18n-label', 'aria-label'], ['data-i18n-content', 'content']]) {
    document.querySelectorAll(`[${attribute}]`).forEach(element => element.setAttribute(target, t(element.getAttribute(attribute))));
  }
  document.querySelectorAll('[data-sample-link]').forEach(link => { link.href = language === 'zh' ? 'examples/sample.txt' : 'examples/sample-en.txt'; });
  document.querySelectorAll('#languageSelect').forEach(select => { select.value = language; });
}

export function setLanguage(next) {
  if (!supported.includes(next)) return;
  language = next;
  try { localStorage.setItem('epubloom.language', language); } catch { /* No storage is required to use the converter. */ }
  renderLanguage();
  window.dispatchEvent(new CustomEvent('epubloom:languagechange'));
}

renderLanguage();
document.querySelector('#languageSelect')?.addEventListener('change', event => setLanguage(event.target.value));
